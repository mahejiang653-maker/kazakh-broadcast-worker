class BingParser(HTMLParser):
    def __init__(self): super().__init__(); self.items=[]
    def handle_starttag(self,tag,attrs):
        if tag!='a': return
        d=dict(attrs); m=d.get('m'); classes=d.get('class','')
        if 'iusc' not in classes or not m:return
        try:o=json.loads(html.unescape(m))
        except Exception:return
        u=o.get('murl') or o.get('turl'); p=o.get('purl') or ''; t=o.get('t') or o.get('desc') or ''
        if u:self.items.append({'download_url':u,'source_page':p,'title':t})

def clean(s): return re.sub(r'<[^>]+>',' ',s or '').replace('&nbsp;',' ').strip()
def blob(*x): return ' '.join(clean(v) for v in x if v).lower()
def reject(*x): return any(k in blob(*x) for k in REJECT)
def topic_ok(item_id,*parts):
    b=blob(*parts); p=STORY[int(item_id)]
    if any(a in b for a in p['avoid']): return False
    return all(any(term in b for term in g) for g in p['groups'])
def years_in(*parts): return [int(x) for x in re.findall(r'(?<!\d)(20(?:2[4-9]|3\d))(?!\d)',blob(*parts))]
def recent_year(*parts):
    ys=years_in(*parts); return max(ys) if ys else None

def verify(data):
    if not data:return None
    try:
        im=Image.open(io.BytesIO(data)); fmt=(im.format or '').upper(); w,h=im.size
        if fmt not in {'JPEG','PNG','WEBP'} or w<MIN_W or h<MIN_H:return None
        # animated/graphic-prone formats are rejected; photographs overwhelmingly arrive as raster JPEG/PNG/WEBP
        return w,h,fmt
    except Exception:return None

def get_bytes(url):
    try:
        r=S.get(url,timeout=30,allow_redirects=True,headers={'Referer':'https://www.bing.com/'}); r.raise_for_status()
        ct=(r.headers.get('content-type') or '').lower()
        if 'svg' in ct or 'text/html' in ct:return None
        return r.content if len(r.content)>20000 else None
    except Exception:return None

def key(c): return hashlib.sha1((c.get('download_url') or c.get('source_page') or c.get('title') or '').encode()).hexdigest()

def commons_search(q,item_id):
    try:
        r=S.get(COMMONS_API,params={'action':'query','format':'json','generator':'search','gsrsearch':q,'gsrnamespace':6,'gsrlimit':COMMONS_LIMIT,'prop':'imageinfo','iiprop':'url|size|mime|extmetadata','iiurlwidth':1800,'redirects':1},timeout=30);r.raise_for_status(); pages=list((r.json().get('query',{}).get('pages') or {}).values())
    except Exception:return []
    out=[]
    for p in pages:
        ii=(p.get('imageinfo') or [{}])[0]; e=ii.get('extmetadata') or {}; title=p.get('title',''); desc=clean(((e.get('ImageDescription') or {}).get('value',''))); cats=clean(((e.get('Categories') or {}).get('value','')))
        dt=clean(((e.get('DateTimeOriginal') or {}).get('value',''))) or clean(((e.get('DateTime') or {}).get('value','')))
        yr=recent_year(dt,title,desc)
        if reject(title,desc,cats) or not topic_ok(item_id,title,desc,cats) or not yr or yr<MIN_RECENT_YEAR:continue
        mime=(ii.get('mime') or '').lower(); ow=int(ii.get('width') or 0);oh=int(ii.get('height') or 0)
        if mime not in {'image/jpeg','image/png','image/webp'} or ow<MIN_W or oh<MIN_H:continue
        out.append({'title':title,'download_url':ii.get('thumburl') or ii.get('url',''),'source_page':ii.get('descriptionurl',''),'source':'Wikimedia Commons','license':clean(((e.get('LicenseShortName') or {}).get('value',''))),'license_url':((e.get('LicenseUrl') or {}).get('value','')),'captured_or_source_date':dt,'recent_year':yr,'recent_evidence':'Commons metadata date','source_tier':'commons-recent-photo'})
    return [x for x in out if x['download_url']]

def openverse_search(q,item_id):
    try:r=S.get(OPENVERSE_API,params={'q':q,'page_size':OPENVERSE_LIMIT,'mature':'false'},timeout=30);r.raise_for_status(); arr=r.json().get('results') or []
    except Exception:return []
    out=[]
    for x in arr:
        url=x.get('url') or x.get('thumbnail') or ''; title=x.get('title') or ''; page=x.get('foreign_landing_url') or ''; created=x.get('created_on') or ''
        yr=recent_year(created,title,page,url)
        if not url or reject(title,page,url) or not topic_ok(item_id,title,page,url) or not yr or yr<MIN_RECENT_YEAR:continue
        out.append({'title':title,'download_url':url,'source_page':page,'source':x.get('source') or 'Openverse','license':((x.get('license') or '')+' '+(x.get('license_version') or '')).strip(),'license_url':x.get('license_url') or '','creator':x.get('creator') or '','captured_or_source_date':created,'recent_year':yr,'recent_evidence':'Openverse created_on / URL-year evidence','source_tier':'openverse-recent-photo'})
    return out

