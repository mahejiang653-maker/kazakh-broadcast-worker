def exact_commons(title,item_id):
    # Exact curated filenames still pass topic and recency checks; no legacy photo is allowed just because it is curated.
    try:
        r=S.get(COMMONS_API,params={'action':'query','format':'json','titles':title,'prop':'imageinfo','iiprop':'url|size|mime|extmetadata','iiurlwidth':1800,'redirects':1},timeout=30);r.raise_for_status(); pages=list((r.json().get('query',{}).get('pages') or {}).values())
    except Exception:return []
    out=[]
    for p in pages:
        ii=(p.get('imageinfo') or [{}])[0];e=ii.get('extmetadata') or {};t=p.get('title',title);desc=clean(((e.get('ImageDescription') or {}).get('value','')));dt=clean(((e.get('DateTimeOriginal') or {}).get('value',''))) or clean(((e.get('DateTime') or {}).get('value','')));yr=recent_year(dt,t,desc)
        if not ii or reject(t,desc) or not topic_ok(item_id,t,desc) or not yr or yr<MIN_RECENT_YEAR:continue
